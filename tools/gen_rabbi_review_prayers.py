#!/usr/bin/env python3
"""Write the «Молитвы на каждый день» part of docs/RABBI-REVIEW.md from
content/ru/prayers.json (dev tool). Replaces the block between the
PRAYERS-BEGIN / PRAYERS-END markers, or appends it."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "RABBI-REVIEW.md")
BEGIN, END = "<!-- PRAYERS-BEGIN -->", "<!-- PRAYERS-END -->"

DOUBTS = """### Что проверить в первую очередь

- [ ] Ссылки на Шульхан Арух, Орах хаим: 62:2, 101:4, 185:1 (молитва на понятном языке), 215:4 (Имя при учёбе), 4 (омовение рук утром), 6 («Ашер яцар»), 46 (утренние благословения), 110:1 («Хавинену»), 110:4–7 (Тфилат а-дерех), 158 (омовение перед хлебом), 167–168, 202–208 (благословения на еду), 187:1 («Брих Рахамана»), 223–225 («Шеэхеяну»), 239 (Шма перед сном), 263 (свечи), 271 (кидуш). Ссылки на Талмуд в каждой молитве ниже.
- [ ] Перевод «Брих Рахамана» и подача краткого Биркат а-мазон: в приложении — «Брих Рахамана» (Брахот 40б) и полное первое благословение («а-Зан»), с советом читать остальное по сидуру. Достаточно ли так и как это сформулировать для начинающего.
- [ ] «Хавинену»: когда её можно говорить вместо полной Амиды (не в зимний сезон дождей, не на исходе Шаббата и праздника, в спешке или в дороге), и правильно ли переданы первые три и последние три благословения.
- [ ] Тфилат а-дерех: текст по сидуру Даат; в других нусахах есть ещё фразы. Нужно ли указать, где её начинают (после выхода из города) и когда говорят без Имени (короткий путь).
- [ ] Порядок «Мезонот / а-Гафен / а-Эц / а-Адама / ше-а-Коль» и правила «Аль а-михья»: варианты для Израиля («аль а-арец ве-аль пероте́а», «ве-аль а-михья»), размеры кезаит и ревиит для благословения после еды.
- [ ] Свечи Шаббата и праздника: текст благословений; что женщина-кандидат до гиюра зажигает свечи без благословения или иначе — подано как «уточните у раввина».
- [ ] Утренние благословения: кандидат до гиюра не говорит «ше-ло асани гой»; после гиюра одни пропускают его, другие говорят «ше-асани гер». Остальные утренние благословения (включая «ше-ло асани авед / иша» и женское «ше-асани ки-рцоно») поданы без отдельной оговорки для кандидата — нужна ли она. Всё помечено «уточните у раввина».
- [ ] Транслитерация Имени («Адонай», «Элоэйну») и совет при учёбе говорить «а-Шем» / «Элокейну». В иврите Имя записано как יְיָ.
- [ ] Шма перед сном: краткий состав (прощение, первый абзац Шма, «а-Мапиль», «Бе-ядо афкид»); перевод «а-Мапиль». Говорит ли его кандидат с Именем.
- [ ] Кидуш: кандидат до гиюра не делает кидуш за других и не говорит «нас Ты избрал… повелел нам»; ревиит дан как «около 86 мл» (есть мнения о бо́льшем объёме).
- [ ] «Модэ ани»: в тексте сказано, что формула появилась в сидурах позже Талмуда (XVI–XVII века). Проверить датировку.
- [ ] Омовение рук утром: по три раза на каждую руку, попеременно; и перед хлебом (два-три раза на каждую руку из сосуда) — разные обычаи.
- [ ] Заметка «Можно молиться на понятном языке»: формулировка, что иврит предпочтителен и первую строку Шма советуют говорить на иврите.

Источники текста: иврит — The Metsudah Siddur (1981, CC-BY) и сидур Даат (общественное достояние), оба через Sefaria, нусах Ашкеназ; знаки кантилляции и метег убраны. Перевод на русский и транслитерация — собственная работа «Шорашим». Тексты благословений на еду, свечи и «Шеэхеяну» — общепринятые формулы."""


def main():
    book = json.load(open(os.path.join(ROOT, "content/ru/prayers.json")))
    groups = {g["id"]: g["title"] for g in book["groups"]}
    out = [BEGIN, "## Молитвы на каждый день", "",
           "Все тексты раздела «Молитвы» (content/ru/prayers.json). Сгенерировано tools/gen_rabbi_review_prayers.py. "
           f"Нусах: {book.get('nusach', '')}. Статус: {book.get('reviewStatus', '')}.", "",
           DOUBTS, "", "### Общие заметки раздела", ""]
    for n in book["notes"]:
        flag = " *(уточните у раввина)*" if n.get("rabbi") else ""
        out.append(f"- [ ] **{n['title']}**{flag}. {n['text']} — *{n.get('ref', '')}*")
    out += ["", "### Тексты молитв", ""]
    for p in book["prayers"]:
        gs = ", ".join(groups.get(g, g) for g in p["groups"])
        out.append(f"#### `{p['id']}` {p['title']} — {p['heTitle']}")
        out.append("")
        out.append(f"- [ ] Проверено. Группы: {gs}. {p.get('subtitle', '')}")
        out.append(f"- **Когда:** {p['when']}")
        out.append(f"- **Как:** {p['how']}")
        out.append(f"- **О молитве:** {p['about']}")
        if p.get("ref"):
            out.append(f"- **Ссылки:** {p['ref']}")
        if p.get("candidate"):
            out.append(f"- **До гиюра:** {p['candidate']}")
        if p.get("source"):
            out.append(f"- **Источник:** {p['source']}")
        out.append("")
        for part in p["parts"]:
            if part.get("label"):
                out.append(f"*{part['label']}*")
                out.append("")
            out.append(f"> {part['he']}")
            out.append(">")
            out.append(f"> *{part['translit']}*")
            out.append(">")
            out.append(f"> {part['ru']}")
            out.append("")
    out.append(END)
    block = "\n".join(out)
    doc = open(DOC, encoding="utf-8").read()
    if BEGIN in doc and END in doc:
        a, b = doc.index(BEGIN), doc.index(END) + len(END)
        doc = doc[:a] + block + doc[b:]
    else:
        doc = doc.rstrip("\n") + "\n\n" + block + "\n"
    open(DOC, "w", encoding="utf-8").write(doc)


if __name__ == "__main__":
    main()
