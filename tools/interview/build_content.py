def build():
    topics = [{"id": i, "title": t, "blurb": b} for i, t, b in TOPICS]
    data = {
        "version": 1,
        "title": "Тренажёр собеседования с бейт-дином",
        "intro": INTRO,
        "sincerity": SINCERITY,
        "topics": topics,
        "questions": Q,
    }
    out = ROOT / "content" / "interview.json"
    out.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return data


def review_md(data):
    titles = {t["id"]: t["title"] for t in data["topics"]}
    lines = [
        "## Тренажёр собеседования с бейт-дином (content/interview.json)",
        "",
        f"Новый раздел: {len(data['questions'])} типичных вопросов бейт-дина в "
        f"{len(data['topics'])} темах. Для каждого вопроса указано, что судьи хотят "
        "проверить, ключевые пункты честного ответа, частые ошибки и ссылки на уроки. "
        "Пожалуйста, проверьте формулировки, верность галахических пунктов и "
        "пометки о различиях течений. Источник правки: `tools/interview/build_content.py`.",
        "",
        "Вводный текст раздела:",
        "",
        "> " + data["intro"],
        "",
    ]
    for t in data["topics"]:
        lines.append(f"### {t['title']}")
        lines.append("")
        for x in data["questions"]:
            if x["topic"] != t["id"]:
                continue
            lines.append(f"- [ ] **`{x['id']}` {x['question']}**")
            lines.append(f"  - Что проверяют: {x['purpose']}")
            lines.append("  - Ключевые пункты: " + " / ".join(x["keyPoints"]))
            lines.append("  - Частые ошибки: " + " / ".join(x["mistakes"]))
            if x.get("movements"):
                lines.append(f"  - Течения: {x['movements']}")
            lines.append("  - Уроки: " + ", ".join(f"`{l}`" for l in x["lessons"]))
        lines.append("")
    _ = titles
    return "\n".join(lines).rstrip() + "\n"


