def format_options(x):
    """Rabbi-review line for the new multiple-choice texts."""
    def one(spec, label=None):
        opts = spec["options"]
        ans = spec["answer"]
        right = opts[ans]
        wrong = [o for i, o in enumerate(opts) if i != ans]
        head = "Варианты ответа (новый текст, нужна проверка)"
        if label:
            head += f", {label}"
        return f"  - {head}: верный: «{right}» / неверные: " + " / ".join(f"«{w}»" for w in wrong)

    by = x.get("optionsByLevel") or {}
    titles = {
        "orthodox": "ортодоксальный путь",
        "conservative": "консервативный путь",
        "reform": "реформистский путь",
    }
    if by:
        lines = [one(by[key], titles[key]) for key in ("orthodox", "conservative", "reform") if key in by]
    else:
        lines = [one(x)]
    return "\n".join(lines)


def review_md(data):
    titles = {t["id"]: t["title"] for t in data["topics"]}
    lines = [
        "## Тренажёр собеседования с бейт-дином (content/interview.json)",
        "",
        f"Новый раздел: {len(data['questions'])} типичных вопросов бейт-дина в "
        f"{len(data['topics'])} темах. Для каждого вопроса указано, что судьи хотят "
        "проверить, ключевые пункты честного ответа, частые ошибки и ссылки на уроки. "
        "Пожалуйста, проверьте формулировки, верность галахических пунктов и "
        "пометки о различиях течений. Источник правки: `tools/interview/build_content.py`.",
        "",
        "Для режимов «Практика» и «Репетиция» к каждому вопросу добавлены "
        "3–4 варианта ответа (верный и правдоподобные, но явно неверные отвлекающие). "
        "Это новый текст, его тоже нужно проверить. Где течения расходятся, варианты "
        "написаны отдельно для ортодоксального, консервативного и реформистского "
        "пути, с равной полнотой. В «Темах» по-прежнему читают вопрос и образец "
        "ответа, без ввода с клавиатуры.",
        "",
        "Вводный текст раздела:",
        "",
        "> " + data["intro"],
        "",
    ]
    for t in data["topics"]:
        lines.append(f"### {t['title']}")
        lines.append("")
        for x in data["questions"]:
            if x["topic"] != t["id"]:
                continue
            lines.append(f"- [ ] **`{x['id']}` {x['question']}**")
            lines.append(f"  - Что проверяют: {x['purpose']}")
            lines.append("  - Ключевые пункты: " + " / ".join(x["keyPoints"]))
            lines.append("  - Частые ошибки: " + " / ".join(x["mistakes"]))
            if x.get("movements"):
                lines.append(f"  - Течения: {x['movements']}")
            lines.append("  - Уроки: " + ", ".join(f"`{l}`" for l in x["lessons"]))
            if x.get("options"):
                lines.append(format_options(x))
        lines.append("")
    _ = titles
    return "\n".join(lines).rstrip() + "\n"


START = "<!-- interview:start -->"
END = "<!-- interview:end -->"


def update_review(data):
    path = ROOT / "docs" / "RABBI-REVIEW.md"
    doc = path.read_text(encoding="utf-8")
    block = f"{START}\n{review_md(data)}{END}\n"
    if START in doc:
        a = doc.index(START)
        b = doc.index(END) + len(END) + 1
        doc = doc[:a] + block + doc[b:]
    else:
        anchor = "## Общие вопросы"
        i = doc.index(anchor)
        doc = doc[:i] + block + "\n" + doc[i:]
    path.write_text(doc, encoding="utf-8")


