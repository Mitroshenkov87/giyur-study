def apply_options():
    """Attach multiple-choice options (and per-movement variants) to each question."""
    validate_options()
    missing = [q["id"] for q in Q if q["id"] not in OPTIONS]
    extra = [i for i in OPTIONS if i not in {q["id"] for q in Q}]
    if missing or extra:
        raise SystemExit(f"options mismatch: missing {missing}, extra {extra}")
    for q in Q:
        spec = OPTIONS[q["id"]]
        q["options"] = spec["options"]
        q["answer"] = spec["answer"]
        if "by_level" in spec:
            q["optionsByLevel"] = {
                lvl: {"options": v["options"], "answer": v["answer"]}
                for lvl, v in spec["by_level"].items()
            }


