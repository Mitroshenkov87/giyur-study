def validate():
    banned = (
        "библи",
        "ветхий завет",
        "ветхого завета",
        "новый завет",
        "нового завета",
        "старый завет",
        "старого завета",
        "христи",
    )
    # typo guard: leftover English in Russian options
    for qid, item in OPTIONS.items():
        chunks = [item]
        if "by_level" in item:
            chunks.extend(item["by_level"].values())
        for ch in chunks:
            opts = ch["options"]
            ans = ch["answer"]
            if not (3 <= len(opts) <= 4):
                raise SystemExit(f"{qid}: {len(opts)} options")
            if ans < 0 or ans >= len(opts):
                raise SystemExit(f"{qid}: bad answer")
            low = " ".join(opts).lower()
            for b in banned:
                if b in low:
                    raise SystemExit(f"{qid}: banned «{b}»")
            if len(set(opts)) != len(opts):
                raise SystemExit(f"{qid}: duplicate option")
            for o in opts:
                if "Occasionally" in o or o != o.strip():
                    raise SystemExit(f"{qid}: typo in option: {o!r}")
    return len(OPTIONS)


