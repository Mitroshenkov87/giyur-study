#!/usr/bin/env python3
"""Regenerate src/calendar/parasha_tables.rs (dev tool, not shipped).

Needs pyluach (MIT): python3 -m venv .venv && .venv/bin/pip install pyluach
For each of the 14 Hebrew year types it lists the reading of every Shabbat
(diaspora and Israel) and asserts that every year 5600-6000 of that type
has the same sequence.
"""
import datetime
from pyluach import dates, parshios


def table(y, israel):
    rh = dates.HebrewDate(y, 7, 1).to_pydate()
    nrh = dates.HebrewDate(y + 1, 7, 1).to_pydate()
    d = rh + datetime.timedelta(days=(5 - rh.weekday()) % 7)
    out = []
    while d < nrh:
        p = parshios.getparsha(dates.GregorianDate(d.year, d.month, d.day), israel)
        if p is None:
            out.append(-1)
        elif len(p) == 1:
            out.append(p[0])
        else:
            assert len(p) == 2 and p[1] == p[0] + 1
            out.append(100 + p[0])
        d += datetime.timedelta(days=7)
    return out


def main():
    types = {}
    for y in range(5600, 6001):
        rh = dates.HebrewDate(y, 7, 1)
        ln = int(dates.HebrewDate(y + 1, 7, 1) - rh)
        types.setdefault((rh.weekday(), ln), y)
    print("// Generated by tools/gen_parasha_tables.py; one row per year type.")
    print("// Key: (weekday of 1 Tishrei, 1=Sunday..7=Shabbat; year length in days).")
    print("// Value: the reading for each Shabbat of the year, in order: -1 = festival")
    print("// reading (no weekly portion), n = portion n (0 = Bereshit), 100+n = n and n+1 together.")
    print("/// (year type, [diaspora, Israel]).")
    print("pub(crate) type YearRow = ((u8, u16), [&'static [i16]; 2]);")
    print("pub(crate) const TABLES: [YearRow; 14] = [")
    for k in sorted(types):
        y = types[k]
        a, b = table(y, False), table(y, True)
        for yy in range(5600, 6001):
            rr = dates.HebrewDate(yy, 7, 1)
            if (rr.weekday(), int(dates.HebrewDate(yy + 1, 7, 1) - rr)) == k:
                assert table(yy, False) == a and table(yy, True) == b, yy
        print(f"    (({k[0]}, {k[1]}), [&{a}, &{b}]),")
    print("];")


if __name__ == "__main__":
    main()
