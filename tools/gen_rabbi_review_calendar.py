#!/usr/bin/env python3
"""Write the «Еврейский календарь» part of docs/RABBI-REVIEW.md from
content/ru/calendar/*.json (dev tool). Replaces the block between the
CALENDAR-BEGIN / CALENDAR-END markers, or appends it."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "RABBI-REVIEW.md")
BEGIN, END = "<!-- CALENDAR-BEGIN -->", "<!-- CALENDAR-END -->"
MOV = {"reform": "Реформистский", "conservative": "Консервативный", "orthodox": "Ортодоксальный"}

RULES = """### Правила расчёта (просьба проверить)

- Еврейская дата: стандартный арифметический календарь (алгоритм Дершовица — Рейнгольда, «Calendrical Calculations»); сверено с независимой реализацией на 1900–2100 гг.
- Диаспора / Израиль — настройка пользователя (по умолчанию: диаспора). В диаспоре вторые дни праздников (Рош а-Шана — два дня везде), Симхат Тора отдельно от Шмини Ацерет, 8-й день Песаха, 2-й день Шавуота.
- Посты и переносы: пост Гедальи с Шаббата → на воскресенье; 17 тамуза и 9 ава с Шаббата → на воскресенье; пост Эстер с Шаббата → на четверг; пост первенцев с Шаббата → на четверг; 10 тевета не переносится (может быть в пятницу).
- Большие посты (Йом Кипур, 9 ава): от заката накануне до выхода звёзд. Малые посты: от рассвета (алот а-шахар, солнце 16,1° под горизонтом) до выхода звёзд.
- Выход звёзд (цейт а-кохавим): солнце 8,5° под горизонтом — для конца Шаббата, праздников и постов. В настройках можно выбрать вместо этого 42, 50 или 72 минуты после заката.
- Зажигание свечей: по умолчанию за 18 минут до заката; можно выбрать 20, 22, 30, 40 (в Иерусалиме принято 40). На второй вечер праздника и в праздник на исходе Шаббата — не раньше выхода звёзд, от существующего огня; в праздник, выпавший на пятницу, — до заката.
- Счёт омера: с вечера 16 нисана, 49 дней; день счёта показывается на дату, вечером накануне которой его считают.
- Три недели: с 17 тамуза до 9 ава; Девять дней: с 1 до 9 ава.
- Особые субботы: Шува (между Рош а-Шана и Йом Кипуром), Шкалим (в или перед Рош Ходеш Адар / Адар II), Захор (перед Пуримом), Пара (за неделю до а-Ходеш), а-Ходеш (в или перед Рош Ходеш Нисан), а-Гадоль (перед Песахом), Хазон (перед 9 ава или в сам день), Нахаму (после 9 ава), Шира (Бешалах).
- Израильские памятные дни: Йом а-Шоа 27 нисана (с пятницы → четверг, с воскресенья → понедельник); Йом а-Ацмаут 5 ияра (с пятницы/субботы → четверг, с понедельника → вторник), Йом а-Зикарон — накануне; Йом Иерушалаим 28 ияра.
- Недельная глава: годовой цикл по Шулхан Аруху (ОХ 428) для всех 14 типов года, отдельно для Израиля и диаспоры; сверено с независимой реализацией на 1990–2060 гг.
- Местоположение: только с согласия пользователя, приблизительно (округление до 0,1°), хранится только на компьютере; либо город из списка, либо координаты вручную.
"""


def main():
    par = json.load(open(os.path.join(ROOT, "content/ru/calendar/parashot.json")))["parashot"]
    days = json.load(open(os.path.join(ROOT, "content/ru/calendar/days.json")))
    out = [BEGIN, "## Еврейский календарь", "",
           "Все тексты раздела «Еврейский календарь» (content/ru/calendar/). Сгенерировано tools/gen_rabbi_review_calendar.py.", "",
           RULES, "### Дни и праздники", ""]
    for d in days["days"]:
        out.append(f"#### `{d['id']}` {d.get('name_he', '')}")
        out.append(f"- **Смысл:** {d.get('meaning', '')}")
        for c in d.get("customs", []):
            out.append(f"- Обычай: {c}")
        out.append(f"- **Мысль дня:** {d.get('idea', '')}")
        if d.get("fast_note"):
            out.append(f"- **Пост:** {d['fast_note']}")
        for k, v in (d.get("movements") or {}).items():
            if v:
                out.append(f"- {MOV.get(k, k)}: {v}")
        if d.get("lessons"):
            out.append(f"- Ссылки на уроки: {', '.join(d['lessons'])}")
        out.append("- [ ] проверено")
        out.append("")
    out += ["### Месяцы", ""]
    for m in days["months"]:
        out.append(f"- `{m['key']}`: {m['idea']} — [ ] проверено")
    out += ["", "### Недельные главы", ""]
    for p in par:
        out.append(f"#### `{p['id']}` ({p.get('ref', '')})")
        out.append(f"- **Кратко:** {p.get('summary', '')}")
        out.append(f"- **Тема:** {p.get('theme', '')}")
        for i, x in enumerate(p.get("daily", [])):
            out.append(f"- {['Вс', 'Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Шаббат'][i]}: {x}")
        out.append("- [ ] проверено")
        out.append("")
    out.append(END)
    block = "\n".join(out) + "\n"
    if os.path.exists(DOC):
        s = open(DOC).read()
        if BEGIN in s:
            s = s[: s.index(BEGIN)] + block + s[s.index(END) + len(END) + 1 :]
        else:
            s = s.rstrip("\n") + "\n\n" + block
    else:
        s = "# Проверка у раввина\n\nСписок текстов и правил приложения для проверки раввином.\n\n" + block
    open(DOC, "w").write(s)


if __name__ == "__main__":
    main()
